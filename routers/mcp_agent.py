@router.post("/orchestrate/create-challenge", response_model=dict)
async def orchestrate_challenge_creation(
    vulnerability_type: VulnerabilityType,
    difficulty: str,
    description: str,
    admin_user: User = Depends(get_current_admin_user),
    llama: LlamaCppService = Depends(get_llama_service)
):
    """
    🔐 ADMIN ONLY: Use MCP agent to generate a complete CTF challenge
    
    Llama.cpp helps admins create challenges with:
    - Vulnerable code
    - Exploitation steps
    - Hints
    - Solutions
    """
    
    # Use Llama to generate challenge details
    prompt = f"""Generate a complete CTF challenge for {vulnerability_type} with {difficulty} difficulty.

Description: {description}

Provide:
1. Challenge title
2. Vulnerable code snippet
3. Step-by-step exploitation guide
4. 3 progressive hints
5. Expected flag format
6. Points value (based on difficulty)

Format as JSON."""
    
    generated = llama.generate_response(prompt, max_tokens=800)
    
    return {
        "success": True,
        "message": "✅ Challenge generated by MCP agent",
        "generated_content": generated,
        "admin": getattr(admin_user, 'username', 'admin'),
        "note": "🤖 Review and customize before deploying to users"
    }


