@router.post("/orchestrate/analyze-user-patterns", response_model=dict)
async def analyze_user_solving_patterns(
    challenge_id: str,
    solve_times: List[int],
    attempt_counts: List[int],
    admin_user: User = Depends(get_current_admin_user),
    llama: LlamaCppService = Depends(get_llama_service)
):
    """
    🔐 ADMIN ONLY: Analyze user solving patterns
    
    MCP agent identifies if challenge is too easy/hard based on data
    """
    
    avg_time = sum(solve_times) / len(solve_times) if solve_times else 0
    avg_attempts = sum(attempt_counts) / len(attempt_counts) if attempt_counts else 0
    
    prompt = f"""Analyze this CTF challenge performance data:

Challenge ID: {challenge_id}
Average solve time: {avg_time} minutes
Average attempts: {avg_attempts}
Total solves: {len(solve_times)}

Provide admin insights:
1. Is difficulty appropriate?
2. Are users stuck on specific parts?
3. Should points be adjusted?
4. Recommendations for improvement
5. Should hints be added/modified?"""
    
    analysis = llama.generate_response(prompt, max_tokens=500)
    
    return {
        "success": True,
        "pattern_analysis": analysis,
        "challenge_id": challenge_id,
        "stats": {
            "avg_solve_time": avg_time,
            "avg_attempts": avg_attempts,
            "total_solves": len(solve_times)
        },
        "admin": getattr(admin_user, 'username', 'admin')
    }


